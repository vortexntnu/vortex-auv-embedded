void SWO_Init(void)
{
    /* Enable ITM and DWT */
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;

    /* ITM unlock */
    ITM->LAR = 0xC5ACCE55;

    /* Enable ITM port 0 */
    ITM->TCR |= ITM_TCR_ITMENA_Msk;
    ITM->TER |= (1UL << 0);  // Enable stimulus port 0
}
